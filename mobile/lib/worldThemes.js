export function resolveTheme(themeOrId) {
  if (!themeOrId) return WORLD_THEMES.dustlands;
  if (typeof themeOrId === 'string') {
    return WORLD_THEMES[themeOrId] || WORLD_THEMES.dustlands;
  }
  const base = WORLD_THEMES[themeOrId.id] || WORLD_THEMES.dustlands;
  return { ...base, ...themeOrId };
}
